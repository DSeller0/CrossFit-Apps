#!/usr/bin/env node
/**
 * Generate the Claude Design cards from the REAL components.
 *
 *   npm run design:cards
 *
 * The in-app gallery (gallery.html) stays the all-states source of truth; these cards
 * are a projection of it — the same role a Lane-A screenshot plays today, but readable
 * and composable, so Claude Design can build layouts out of actual component markup.
 * Nothing here is hand-maintained: re-run after touching a component and re-sync.
 *
 * How: vite.design.config.js SSR-builds scripts/design-cards-entry.jsx (which re-exports
 * the gallery's GROUPS) plus one CSS asset with deterministic class names. We render each
 * group to static HTML and inline themes.css + that CSS + base64 fonts, so each card is
 * self-contained — Claude Design's CSP blocks every external request.
 */
import { build } from 'vite'
import { renderToStaticMarkup } from 'react-dom/server'
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'fs'
import { resolve, dirname } from 'path'
import { fileURLToPath, pathToFileURL } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const CONE  = resolve(__dirname, '..')
const REPO  = resolve(CONE, '..')
const OUT   = resolve(CONE, 'design')
const BUILD = resolve(CONE, '.design-build')

const BANNER = 'GENERATED by `npm run design:cards` — do not edit.\n     Source: the real components via src/public/gallery/Gallery.jsx (GROUPS).\n     Edit the component, re-run, re-sync. See design/README.md.'

// Latin woff2 subsets for the weights src/fonts.js actually loads. Inlined as base64
// because a card cannot fetch anything. Missing files are skipped with a warning
// rather than failing the run.
const FONTS = [
  ['Cinzel',      400, '@fontsource/cinzel/files/cinzel-latin-400-normal.woff2'],
  ['Cinzel',      500, '@fontsource/cinzel/files/cinzel-latin-500-normal.woff2'],
  ['Cinzel',      600, '@fontsource/cinzel/files/cinzel-latin-600-normal.woff2'],
  ['Cinzel',      700, '@fontsource/cinzel/files/cinzel-latin-700-normal.woff2'],
  ['Cinzel',      800, '@fontsource/cinzel/files/cinzel-latin-800-normal.woff2'],
  ['Cinzel',      900, '@fontsource/cinzel/files/cinzel-latin-900-normal.woff2'],
  ['Crimson Pro', 400, '@fontsource/crimson-pro/files/crimson-pro-latin-400-normal.woff2'],
  ['Crimson Pro', 600, '@fontsource/crimson-pro/files/crimson-pro-latin-600-normal.woff2'],
  ['Amarante',    400, '@fontsource/amarante/files/amarante-latin-400-normal.woff2'],
]

const THEME_LABELS = {
  'totk-dark':            'TotK Dark',
  'totk-light':           'TotK Light',
  'spirit-blossom':       'Spirit Blossom',
  'spirit-blossom-light': 'Spirit Blossom Light',
}

const esc = str => String(str).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

function fontFaces() {
  let css = ''
  for (const [family, weight, rel] of FONTS) {
    const file = resolve(CONE, 'node_modules', rel)
    if (!existsSync(file)) { console.warn(`  ! font missing, skipped: ${rel}`); continue }
    const b64 = readFileSync(file).toString('base64')
    css += `@font-face{font-family:'${family}';font-style:normal;font-weight:${weight};font-display:swap;`
        +  `src:url(data:font/woff2;base64,${b64}) format('woff2')}\n`
  }
  return css
}

/** themes.css `html.theme-*{ --tok:val; }` blocks → [{ cls, label, vars }] */
function parseThemes(css) {
  const out = []
  const re = /html\.theme-([a-z-]+)\s*\{([^}]+)\}/g
  let m
  while ((m = re.exec(css))) {
    const vars = {}
    for (const decl of m[2].split(';')) {
      const i = decl.indexOf(':')
      if (i < 0) continue
      const k = decl.slice(0, i).trim()
      if (k.startsWith('--')) vars[k] = decl.slice(i + 1).trim()
    }
    out.push({ cls: m[1], label: THEME_LABELS[m[1]] || m[1], vars })
  }
  return out
}

const CHROME = `
  html,body{margin:0}
  body{background:var(--bg);color:var(--text);font-family:var(--font);padding:0 0 40px}
  .dsBar{display:flex;align-items:center;justify-content:space-between;gap:16px;flex-wrap:wrap;
    padding:14px 20px;border-bottom:1px solid var(--divider);background:var(--stone);margin-bottom:8px}
  .dsBarT{font-size:13px;font-weight:700;letter-spacing:.14em;text-transform:uppercase;color:var(--cream)}
  .dsBarT small{display:block;font-weight:400;letter-spacing:.04em;text-transform:none;
    font-size:11px;color:var(--muted);margin-top:3px}
  .dsBar label{display:flex;align-items:center;gap:8px;font-size:11px;letter-spacing:.1em;
    text-transform:uppercase;color:var(--sub)}
  .dsBar select{background:var(--stone2);color:var(--cream);border:1px solid var(--divider);
    font-family:inherit;font-size:12px;padding:5px 8px}
  .dsWrap{padding:0 20px}
`

function card({ file, group, title, subtitle, body, extraCss = '', themes }) {
  const opts = themes.map(t => `<option value="${t.cls}">${esc(t.label)}</option>`).join('')
  const html = `<!-- @dsCard group="${group}" -->
<!-- ${BANNER} -->
<meta charset="utf-8">
<title>${esc(title)}</title>
<style>${fontFaces()}</style>
<style>${readFileSync(resolve(REPO, 'themes.css'), 'utf8')}</style>
<style>${extraCss}</style>
<style>${CHROME}</style>
<body>
<div class="dsBar">
  <div class="dsBarT">${esc(title)}<small>${esc(subtitle)}</small></div>
  <label>Tema <select id="dsTheme">${opts}</select></label>
</div>
<div class="dsWrap">
${body}
</div>
<script>
(function () {
  var sel = document.getElementById('dsTheme')
  function apply(v) { document.documentElement.className = 'theme-' + v }
  sel.addEventListener('change', function () { apply(sel.value) })
  apply(sel.value)
})()
</script>
</body>
`
  const dest = resolve(OUT, file)
  mkdirSync(dirname(dest), { recursive: true })
  writeFileSync(dest, html)
  const kb = (Buffer.byteLength(html) / 1024).toFixed(0)
  console.log(`  ✓ design/${file.padEnd(28)} ${kb.padStart(4)} KB`)
}

// ── Palette card — generated from themes.css so it can never drift again ──────
// (The hand-written card documented 13 vars; themes.css carries 30, including the
// --podium-* tokens added since. That is exactly the drift this kills.)
function paletteCard(themes) {
  const isColor = v => /^#|^rgb|^hsl/.test(v)
  const panels = themes.map(t => {
    const colors = Object.entries(t.vars).filter(([, v]) => isColor(v))
    const other  = Object.entries(t.vars).filter(([, v]) => !isColor(v))
    const sw = colors.map(([k, v]) =>
      `<div class="pSw"><div class="pChip" style="background:${v}"></div>` +
      `<div class="pLbl"><span>${esc(k)}</span><span>${esc(v)}</span></div></div>`).join('')
    const ot = other.map(([k, v]) =>
      `<div class="pVar"><span>${esc(k)}</span><span>${esc(v)}</span></div>`).join('')
    return `<section class="pTheme theme-${t.cls}">
  <h2 class="pName">${esc(t.label)}<code>html.theme-${t.cls}</code></h2>
  <div class="pGrid">${sw}</div>
  <div class="pVars">${ot}</div>
</section>`
  }).join('\n')

  card({
    file: 'tokens/palette.html',
    group: 'Tokens',
    title: 'Cone — Palette',
    subtitle: `${themes.length} temas · ${Object.keys(themes[0].vars).length} tokens cada · gerado de themes.css`,
    themes,
    extraCss: `
      .pTheme{background:var(--bg);color:var(--text);border:1px solid var(--divider);padding:16px;margin-bottom:20px}
      .pName{font-size:12px;letter-spacing:.14em;text-transform:uppercase;margin:0 0 12px;
        display:flex;align-items:baseline;gap:10px}
      .pName code{font-family:Consolas,monospace;font-size:10px;color:var(--muted);letter-spacing:0;text-transform:none}
      .pGrid{display:grid;grid-template-columns:repeat(auto-fill,minmax(132px,1fr));gap:8px}
      .pSw{border:1px solid var(--divider)}
      .pChip{height:42px}
      .pLbl,.pVar{display:flex;justify-content:space-between;gap:6px;font-family:Consolas,monospace;font-size:10px;padding:5px 7px}
      .pLbl span:last-child,.pVar span:last-child{color:var(--muted)}
      .pVars{margin-top:10px;border-top:1px solid var(--divider);padding-top:8px}
      .pVar{padding:3px 0}
    `,
    // Each panel re-declares the theme locally, so all four render at once regardless
    // of the switcher — the switcher only restyles the surrounding chrome.
    body: panels,
  })
}

async function main() {
  console.log('▸ SSR-building the gallery components…')
  await build({ configFile: resolve(CONE, 'vite.design.config.js'), logLevel: 'warn' })

  const cssFile = readdirSync(resolve(BUILD, 'assets')).find(f => f.endsWith('.css'))
  if (!cssFile) throw new Error('No CSS asset emitted — check build.ssrEmitAssets in vite.design.config.js')
  const componentCss = readFileSync(resolve(BUILD, 'assets', cssFile), 'utf8')

  // Nav's isNavHidden() reads the query string at render time. A card is a page with
  // no query string, so an empty search is the faithful value.
  globalThis.window ??= { location: { search: '' } }

  const { GROUPS } = await import(pathToFileURL(resolve(BUILD, 'design-cards-entry.js')).href)
  const themes = parseThemes(readFileSync(resolve(REPO, 'themes.css'), 'utf8'))
  if (themes.length !== 4) throw new Error(`Expected 4 themes in themes.css, parsed ${themes.length}`)

  console.log('▸ Rendering cards…')
  const skipped = []
  for (const g of GROUPS) {
    if (!g.items.length) continue
    let body = ''
    for (const item of g.items) {
      try {
        body += renderToStaticMarkup(item.render())
      } catch (e) {
        skipped.push(`${g.group}/${item.id}: ${e.message.split('\n')[0]}`)
      }
    }
    // A card cannot load the Tabler *webfont* (CSP blocks the CDN), so `ti ti-*` icons
    // render as blank gaps. Components on @tabler/icons-react inline their SVG and are
    // fine. Say so on the card itself — otherwise the gaps read as a broken component.
    // (The icon-language decision is #53/B4's; this note goes away when it lands.)
    const tiCount = (body.match(/class="ti ti-/g) || []).length
    const note = tiCount
      ? ` — ⚠ ${tiCount} ícones da webfont "ti" não renderizam num card (CSP bloqueia o CDN); no app aparecem normalmente.`
      : ''

    card({
      file: `components/${g.group.toLowerCase()}.html`,
      group: 'Components',
      title: `Cone — ${g.group}`,
      subtitle: g.items.map(i => i.label).join(' · ') + note,
      extraCss: componentCss,
      themes,
      body,
    })
  }

  paletteCard(themes)

  if (skipped.length) {
    console.log('\n! Skipped:')
    for (const s of skipped) console.log('  - ' + s)
    process.exitCode = 1
  } else {
    console.log('\n✓ All components rendered. Sync with DesignSync (see design/README.md).')
  }
}

main().catch(e => { console.error(e); process.exit(1) })
