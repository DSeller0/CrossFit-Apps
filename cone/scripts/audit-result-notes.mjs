// #116 · Per-exercise adaptation notes — real-data audit. Read-only, run any time from cone/:
//   node scripts/audit-result-notes.mjs
// → prints a summary and rewrites docs/reviews/116-result-notes-audit.md. Uses .env.production
// (anon read: results_v2 is anon-readable, so no service-role key).
//
// The point of the feature is to derive the eventual structured vocabulary from what coaches
// and athletes actually type, the same method #94 used to take registry misses 58.5% → 11.9%
// — so this is meant to be RE-RUN as real notes accumulate, not a one-time snapshot.
import { readFileSync, writeFileSync } from 'node:fs'
import { createClient } from '@supabase/supabase-js'

const env = readFileSync('./.env.production', 'utf8')
const get = k => (env.match(new RegExp('^' + k + '=(.*)$', 'm')) || [])[1]?.trim()
const sb = createClient(get('VITE_SUPABASE_URL'), get('VITE_SUPABASE_ANON_KEY'))

const { data: results, error } = await sb.from('results_v2').select('*')
if (error) {
  console.error('results_v2 read failed:', error.message)
  process.exit(1)
}

const rows = results || []
const entries = []
rows.forEach(r =>
  (r.blocks || []).forEach(b =>
    entries.push({ ...b, _rowId: r.id, _ath: r.athlete_id, _date: r.date }),
  ),
)

const withNotes = entries.filter(e => Array.isArray(e.exerciseRows) && e.exerciseRows.length)
const notes = withNotes.flatMap(e =>
  e.exerciseRows.map(row => ({ ...row, _date: e._date, _scale: e.scale, _block: e.blockLabel })),
)

const tally = arr => {
  const m = new Map()
  arr.forEach(v => m.set(v, (m.get(v) || 0) + 1))
  return [...m.entries()].sort((a, b) => b[1] - a[1])
}

const byExercise = tally(notes.map(n => n.name || '(sem nome)'))
const pct = (n, d) => (d ? `${((n / d) * 100).toFixed(1)}%` : '—')

const md = `# #116 — per-exercise adaptation notes audit

> Generated by \`node scripts/audit-result-notes.mjs\` · ${new Date().toISOString().slice(0, 10)}
> Re-run as real notes accumulate — this is the same real-data-first method #94 used for the
> registry resolver, applied to \`exerciseRows\`' free text.

**Corpus:** ${rows.length} \`results_v2\` rows · ${entries.length} block entries · **${withNotes.length}**
entries carry at least one adaptation note (${pct(withNotes.length, entries.length)}).

## Notes by exercise

${
  byExercise.length
    ? byExercise.map(([name, n]) => `- **${name}** × ${n}`).join('\n')
    : '_None yet._ The feature just shipped — re-run this after a few weeks of real logging.'
}

## Every note, verbatim

${
  notes.length
    ? `| date | scale | block | exercise | note |\n|---|---|---|---|---|\n${notes
        .map(
          n =>
            `| ${n._date} | ${n._scale || '—'} | ${n._block || '—'} | ${n.name || '—'} | ${(n.note || '').replace(/\|/g, '\\|')} |`,
        )
        .join('\n')}`
    : '_None yet._'
}
`

writeFileSync('docs/reviews/116-result-notes-audit.md', md)

console.log(`
per-exercise adaptation notes audit  ·  ${rows.length} rows / ${entries.length} block entries

entries with a note      ${withNotes.length} of ${entries.length} (${pct(withNotes.length, entries.length)})
distinct exercises noted ${byExercise.length}
${byExercise.length ? byExercise.map(([v, n]) => `  - ${v} × ${n}`).join('\n') : ''}

→ docs/reviews/116-result-notes-audit.md
`)
